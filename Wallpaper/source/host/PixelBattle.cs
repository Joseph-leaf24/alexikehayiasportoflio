// Pixel Battle: the Site 2 pixel battle as a live Windows desktop wallpaper, in one exe.
//
// The battle's page and the WebView2 DLLs are embedded as resources and unpacked to
// %LOCALAPPDATA%\PixelBattle\app\<build stamp> on first run. Needs only what Windows 10/11
// ship with: .NET Framework 4.8 and the WebView2 runtime.
//
// Command line:
//   --exit       closes the running instance and restores the normal wallpaper
//   --selftest   attaches, runs a scripted sleep/wake cycle, writes selftest.log, exits
//                (--seconds=N sets how long it stays awake)
//   --log        runs normally and writes log.txt on exit
//   --startup    used by the "Start with Windows" entry: skips the greeting
//
// Built by scripts/build-exe.mjs with the C# 5 compiler that ships with .NET Framework 4.
// Build.g.cs, which defines Build.Stamp, is generated by that script.
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Drawing;
using System.Globalization;
using System.IO;
using System.IO.Compression;
using System.Reflection;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;
using System.Text;
using System.Threading;
using System.Threading.Tasks;
using System.Windows.Forms;
using Microsoft.Web.WebView2.Core;
using Microsoft.Web.WebView2.WinForms;
using Microsoft.Win32;

namespace PixelBattle
{
    static class Program
    {
        public const string QuitEvent = "Local\\PixelBattleWallpaperQuit";
        public const string ShowEvent = "Local\\PixelBattleWallpaperShow";

        [STAThread]
        static int Main(string[] args)
        {
            if (Has(args, "--exit"))
            {
                Signal(QuitEvent);
                return 0;
            }

            bool test = Has(args, "--selftest");
            bool first;
            using (var mutex = new Mutex(true, "Local\\PixelBattleWallpaper", out first))
            {
                if (!first && !test)
                {
                    // Already running: ask that instance to say so, then leave.
                    Signal(ShowEvent);
                    return 0;
                }

                Application.EnableVisualStyles();
                Application.SetCompatibleTextRenderingDefault(false);
                try
                {
                    Payload.Unpack(first && !test);
                }
                catch (Exception e)
                {
                    MessageBox.Show(
                        "Pixel Battle couldn't unpack itself into " + Payload.Folder + ".\n\n" + e.Message,
                        "Pixel Battle",
                        MessageBoxButtons.OK,
                        MessageBoxIcon.Error);
                    return 1;
                }

                AppDomain.CurrentDomain.AssemblyResolve += Payload.Resolve;
                Run(test, Has(args, "--startup"), test || Has(args, "--log"));
            }
            return 0;
        }

        // Kept out of Main so no WebView2 type is loaded before AssemblyResolve is registered.
        [MethodImpl(MethodImplOptions.NoInlining)]
        static void Run(bool test, bool startup, bool logging)
        {
            Application.Run(new Host(test, startup, logging));
        }

        static bool Has(string[] args, string flag)
        {
            return Array.IndexOf(args, flag) >= 0;
        }

        static void Signal(string name)
        {
            EventWaitHandle handle;
            if (EventWaitHandle.TryOpenExisting(name, out handle))
            {
                using (handle) handle.Set();
            }
        }
    }

    /// <summary>The battle page and WebView2 DLLs embedded in the exe.</summary>
    static class Payload
    {
        const string Prefix = "payload/";

        /// <summary>One folder per build, so a new exe never runs files unpacked by an old one.</summary>
        public static readonly string Folder = Path.Combine(Settings.Folder, "app", Build.Stamp);

        /// <summary>
        /// Unpacks any missing files (each written to a .part file, then moved into place).
        /// With <paramref name="tidy"/>, deletes the folders older builds unpacked.
        /// </summary>
        public static void Unpack(bool tidy)
        {
            var assembly = typeof(Payload).Assembly;
            foreach (var name in assembly.GetManifestResourceNames())
            {
                if (!name.StartsWith(Prefix, StringComparison.Ordinal) || !name.EndsWith(".gz", StringComparison.Ordinal))
                    continue;
                var relative = name.Substring(Prefix.Length, name.Length - Prefix.Length - 3)
                    .Replace('/', Path.DirectorySeparatorChar);
                var target = Path.Combine(Folder, relative);
                if (File.Exists(target)) continue;

                Directory.CreateDirectory(Path.GetDirectoryName(target));
                var part = target + "." + Process.GetCurrentProcess().Id + ".part";
                using (var resource = assembly.GetManifestResourceStream(name))
                using (var gzip = new GZipStream(resource, CompressionMode.Decompress))
                using (var file = File.Create(part))
                {
                    gzip.CopyTo(file);
                }
                try
                {
                    File.Move(part, target);
                }
                catch (IOException)
                {
                    // Another instance (a self-test) unpacked the same file first.
                    File.Delete(part);
                    if (!File.Exists(target)) throw;
                }
            }

            if (!tidy) return;
            try
            {
                foreach (var dir in Directory.GetDirectories(Path.GetDirectoryName(Folder)))
                {
                    if (string.Equals(Path.GetFileName(dir), Build.Stamp, StringComparison.OrdinalIgnoreCase)) continue;
                    try { Directory.Delete(dir, true); }
                    catch (Exception) { }
                }
            }
            catch (Exception) { }
        }

        public static Assembly Resolve(object sender, ResolveEventArgs e)
        {
            var path = Path.Combine(Folder, new AssemblyName(e.Name).Name + ".dll");
            return File.Exists(path) ? Assembly.LoadFrom(path) : null;
        }

        /// <summary>The embedded icon at the size the tray uses.</summary>
        public static Icon TrayIcon()
        {
            try
            {
                using (var stream = typeof(Payload).Assembly.GetManifestResourceStream("PixelBattle.ico"))
                {
                    if (stream != null) return new Icon(stream, SystemInformation.SmallIconSize);
                }
            }
            catch (Exception) { }
            return Icon.ExtractAssociatedIcon(Application.ExecutablePath);
        }
    }

    /// <summary>User settings, stored as key=value lines in %LOCALAPPDATA%\PixelBattle\settings.txt.</summary>
    sealed class Settings
    {
        public double Speed = 2;
        public int Zoom = 75;
        public int Fps = 30;
        public bool AllScreens = false;
        public bool Clicks = true;
        // Off by default: on a laptop that is often unplugged the battle would rarely show.
        public bool PauseOnBattery = false;

        public static string Folder
        {
            get { return Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "PixelBattle"); }
        }

        public static string DataFolder
        {
            get { return Path.Combine(Folder, "WebView2"); }
        }

        static string FileName
        {
            get { return Path.Combine(Folder, "settings.txt"); }
        }

        /// <summary>Reads the settings file; missing, unreadable or out-of-range values keep their defaults.</summary>
        public static Settings Load()
        {
            var s = new Settings();
            try
            {
                if (!File.Exists(FileName)) return s;
                var c = CultureInfo.InvariantCulture;
                foreach (var line in File.ReadAllLines(FileName))
                {
                    var kv = line.Split(new[] { '=' }, 2);
                    if (kv.Length != 2) continue;
                    var key = kv[0].Trim();
                    var value = kv[1].Trim();
                    double d;
                    int n;
                    if (key == "speed" && double.TryParse(value, NumberStyles.Float, c, out d) && d >= 0.5 && d <= 8)
                        s.Speed = d;
                    else if (key == "zoom" && int.TryParse(value, NumberStyles.Integer, c, out n) && n >= 50 && n <= 100)
                        s.Zoom = n;
                    else if (key == "fps" && int.TryParse(value, NumberStyles.Integer, c, out n) && n >= 10 && n <= 120)
                        s.Fps = n;
                    else if (key == "screens") s.AllScreens = value == "all";
                    else if (key == "clicks") s.Clicks = value != "off";
                    else if (key == "battery") s.PauseOnBattery = value == "pause";
                }
            }
            catch (Exception) { }
            return s;
        }

        public void Save()
        {
            try
            {
                Directory.CreateDirectory(Folder);
                var c = CultureInfo.InvariantCulture;
                File.WriteAllLines(FileName, new[]
                {
                    "speed=" + Speed.ToString(c),
                    "zoom=" + Zoom.ToString(c),
                    "fps=" + Fps.ToString(c),
                    "screens=" + (AllScreens ? "all" : "main"),
                    "clicks=" + (Clicks ? "on" : "off"),
                    "battery=" + (PauseOnBattery ? "pause" : "run"),
                });
            }
            catch (Exception) { }
        }

        /// <summary>The settings as the page's query string.</summary>
        public string Query()
        {
            return string.Format(CultureInfo.InvariantCulture, "?speed={0}&zoom={1}&fps={2}", Speed, Zoom, Fps);
        }

        /// <summary>The settings as a script for a page that is already running.</summary>
        public string Script()
        {
            return string.Format(
                CultureInfo.InvariantCulture,
                "window.battle && (battle.set('speed', {0}), battle.set('zoom', {1}), battle.set('fps', {2}))",
                Speed, Zoom, Fps);
        }
    }

    /// <summary>The app: tray icon and menu, one <see cref="Wall"/> per screen, and the once-a-second sleep check.</summary>
    sealed class Host : ApplicationContext
    {
        const string RunKey = "Software\\Microsoft\\Windows\\CurrentVersion\\Run";
        const int MaxTooltip = 63;
        static readonly TimeSpan LostDesktopGrace = TimeSpan.FromSeconds(15);

        // NotifyIcon only opens its menu on right-click; this private method opens it for a left-click too.
        static readonly MethodInfo ShowContextMenu =
            typeof(NotifyIcon).GetMethod("ShowContextMenu", BindingFlags.Instance | BindingFlags.NonPublic);

        readonly Settings settings = Settings.Load();
        readonly List<Wall> walls = new List<Wall>();
        readonly NotifyIcon tray = new NotifyIcon();
        readonly System.Windows.Forms.Timer watch = new System.Windows.Forms.Timer();
        readonly string battle = Path.Combine(Payload.Folder, "battle");
        readonly bool test;
        readonly bool startup;
        readonly bool logging;
        readonly StringBuilder log = new StringBuilder();
        CoreWebView2Environment env;
        MouseHook hook;
        Signals signals;
        bool paused;
        bool locked;
        bool greeted;
        bool finished;
        bool pressing;
        DateTime lostSince = DateTime.MinValue;
        bool toldLost;
        string status = "";
        ToolStripMenuItem pauseItem;

        public Host(bool selftest, bool atStartup, bool keepLog)
        {
            test = selftest;
            startup = atStartup;
            logging = keepLog;

            tray.Icon = Payload.TrayIcon();
            tray.Text = "Pixel Battle (your live wallpaper)";
            tray.Visible = !test;
            tray.ContextMenuStrip = BuildMenu();
            tray.MouseUp += delegate (object sender, MouseEventArgs e)
            {
                if (e.Button == MouseButtons.Left && ShowContextMenu != null) ShowContextMenu.Invoke(tray, null);
            };

            watch.Interval = 1000;
            watch.Tick += delegate { Watch(); };
            SystemEvents.DisplaySettingsChanged += OnDisplays;
            SystemEvents.SessionSwitch += OnSession;
            signals = new Signals(Rebuild);
            hook = new MouseHook(OnMouse);

            if (!test)
            {
                // Rewrite the startup entry so it follows the exe if it has been moved.
                if (StartsWithWindows()) SetStartWithWindows(true);
                Listen();
            }
            Log("Pixel Battle " + Build.Stamp + ", unpacked in " + Payload.Folder);
            Log("tray icon: a left click opens the menu: " + (ShowContextMenu != null));
            Start();
        }

        void Log(string line)
        {
            if (!logging) return;
            log.AppendLine(DateTime.Now.ToString("HH:mm:ss.fff", CultureInfo.InvariantCulture) + " " + line);
        }

        /// <summary>Waits for another PixelBattle.exe asking this one to quit (--exit) or to say it is running.</summary>
        void Listen()
        {
            var quit = new EventWaitHandle(false, EventResetMode.AutoReset, Program.QuitEvent);
            var show = new EventWaitHandle(false, EventResetMode.AutoReset, Program.ShowEvent);
            var ui = SynchronizationContext.Current ?? new WindowsFormsSynchronizationContext();
            var waiter = new Thread(delegate ()
            {
                while (true)
                {
                    if (WaitHandle.WaitAny(new WaitHandle[] { quit, show }) == 0)
                    {
                        ui.Post(delegate { Finish(); }, null);
                        return;
                    }
                    ui.Post(delegate
                    {
                        Tell("Pixel Battle is already your wallpaper",
                            "Right-click its icon by the clock for its settings, or Exit to put your own wallpaper back.");
                    }, null);
                }
            });
            waiter.IsBackground = true;
            waiter.Start();
        }

        void Tell(string title, string text)
        {
            if (!test && !finished) tray.ShowBalloonTip(8000, title, text, ToolTipIcon.Info);
        }

        async void Start()
        {
            if (!File.Exists(Path.Combine(battle, "index.html")))
            {
                MessageBox.Show("The battle's page is missing from " + battle + ".", "Pixel Battle",
                    MessageBoxButtons.OK, MessageBoxIcon.Error);
                Finish();
                return;
            }

            try
            {
                try { CoreWebView2Environment.SetLoaderDllFolderPath(Payload.Folder); }
                catch (Exception) { Native.LoadLibrary(Path.Combine(Payload.Folder, "WebView2Loader.dll")); }

                // The page always sits under the desktop icons, so WebView2's own occlusion throttling
                // would stall it; this app decides when it sleeps instead.
                var options = new CoreWebView2EnvironmentOptions(
                    "--disable-features=CalculateNativeWinOcclusion " +
                    "--disable-backgrounding-occluded-windows --disable-renderer-backgrounding");
                env = await CoreWebView2Environment.CreateAsync(null, Settings.DataFolder, options);
                Log("WebView2 " + env.BrowserVersionString);
            }
            catch (Exception e)
            {
                Log("no WebView2: " + e.Message);
                if (!test)
                {
                    MessageBox.Show(
                        "Pixel Battle needs Microsoft Edge WebView2, which comes with Windows 11 " +
                        "(and with Windows 10's updates).\n\nIt can be installed from microsoft.com/edge/webview2.\n\n" +
                        e.Message,
                        "Pixel Battle", MessageBoxButtons.OK, MessageBoxIcon.Error);
                }
                Finish();
                return;
            }

            // The self-test starts asleep, like a launch behind covering windows: the page is
            // suspended before it has loaded.
            if (test) paused = true;
            Attach();
            Greet();
            watch.Start();
            if (test) await RunSelfTest();
        }

        /// <summary>Wakes, sleeps (changing the settings meanwhile) and wakes again, logging what the page reports.</summary>
        async Task RunSelfTest()
        {
            await Task.Delay(4000);
            paused = false;
            Watch();

            int seconds = 9;
            foreach (var a in Environment.GetCommandLineArgs())
            {
                if (a.StartsWith("--seconds=")) int.TryParse(a.Substring(10), out seconds);
            }
            await Task.Delay(seconds * 1000);
            foreach (var w in walls)
            {
                Log(w.Report() + string.Format(CultureInfo.InvariantCulture,
                    "; its desktop behind windows now: {0:0}%", Covered.Share(w.Screen) * 100));
            }

            // Settings changed while asleep must be in force when it wakes.
            paused = true;
            Watch();
            await Task.Delay(1500);
            settings.Speed = 4;
            settings.Zoom = 50;
            settings.Fps = 20;
            SettingsChanged();
            Log("settings changed while asleep: speed 4, zoom 50, fps 20");
            await Task.Delay(2500);
            paused = false;
            Watch();
            await Task.Delay(6000);
            foreach (var w in walls) Log("after waking: " + w.Report());
            Finish();
        }

        /// <summary>Puts a wall on each screen in use, behind the desktop icons.</summary>
        void Attach()
        {
            if (env == null || finished) return;
            if (!Desktop.Find())
            {
                // Retried every second by Watch. Explorer restarting, or still starting at sign-in,
                // takes a few seconds, so only report it once it has been missing for a while.
                if (lostSince == DateTime.MinValue)
                {
                    lostSince = DateTime.Now;
                    Log("no desktop window found");
                }
                if (!toldLost && DateTime.Now - lostSince > LostDesktopGrace)
                {
                    toldLost = true;
                    Tell("Pixel Battle couldn't find the desktop",
                        "It keeps trying. If the battle doesn't come back, Exit in its tray menu and run it again.");
                }
                return;
            }

            lostSince = DateTime.MinValue;
            toldLost = false;
            Log("desktop: " + Desktop.Describe());
            var screens = settings.AllScreens ? Screen.AllScreens : new[] { Screen.PrimaryScreen };
            foreach (var screen in screens)
            {
                var wall = new Wall(screen, logging ? (Action<string>)Log : null, settings.Script);
                walls.Add(wall);
                wall.Open(env, battle, settings.Query() + (test ? "&report=1" : ""));
            }
        }

        /// <summary>A one-off notification on a manual start, saying why the battle may not be visible yet.</summary>
        void Greet()
        {
            if (greeted || startup || walls.Count == 0) return;
            greeted = true;

            bool hidden = false;
            foreach (var w in walls) hidden |= Covered.Over(w.Screen);
            string now;
            if (OnBattery())
                now = "It's asleep while you're on battery, to save it: plug in to see it, or untick Sleep on battery in its menu. ";
            else if (hidden)
                now = "It's behind your windows for now (it sleeps while they cover the desktop): Win+D shows it. ";
            else
                now = "It plays behind your desktop icons; click the desktop for a blast. ";
            Tell("Pixel Battle is now your wallpaper",
                now + "Click its icon by the clock for settings, Start with Windows, or Exit.");
        }

        /// <summary>Recreates every wall: after Explorer restarts, the screens change, or the screen setting does.</summary>
        void Rebuild()
        {
            foreach (var w in walls) w.Close();
            walls.Clear();
            Attach();
        }

        void OnDisplays(object sender, EventArgs e)
        {
            Rebuild();
        }

        void OnSession(object sender, SessionSwitchEventArgs e)
        {
            switch (e.Reason)
            {
                case SessionSwitchReason.SessionLock:
                case SessionSwitchReason.ConsoleDisconnect:
                case SessionSwitchReason.RemoteDisconnect:
                    locked = true;
                    break;
                case SessionSwitchReason.SessionUnlock:
                case SessionSwitchReason.ConsoleConnect:
                case SessionSwitchReason.RemoteConnect:
                    locked = false;
                    break;
            }
            Watch();
        }

        /// <summary>Runs every second: wakes each wall that can be seen and puts the others to sleep.</summary>
        void Watch()
        {
            if (env == null || finished) return;
            if (!Desktop.Alive())
            {
                Rebuild();
                return;
            }

            bool battery = OnBattery();
            string state = paused ? "paused" : locked ? "asleep (PC locked)" : battery ? "asleep (on battery)" : null;
            foreach (var w in walls)
            {
                double share = test ? 0 : Covered.Share(w.Screen);
                bool covered = share >= Covered.Threshold;
                bool awake = !paused && !locked && !battery && !covered;
                var decision = string.Format("{0}: {1} (covered {2}, paused {3}, locked {4}, on battery {5})",
                    w.Screen.DeviceName, awake ? "to be seen" : "to sleep", covered, paused, locked, battery);
                if (decision != w.LastDecision)
                {
                    w.LastDecision = decision;
                    Log(decision + string.Format(CultureInfo.InvariantCulture,
                        ", {0:0}% of its desktop behind windows", share * 100));
                }
                w.Awake(awake);
                if (state == null && covered) state = "asleep (windows cover it)";
            }
            ShowStatus(state ?? "playing");
        }

        bool OnBattery()
        {
            return settings.PauseOnBattery && SystemInformation.PowerStatus.PowerLineStatus == PowerLineStatus.Offline;
        }

        void ShowStatus(string state)
        {
            var text = "Pixel Battle: " + state;
            if (text == status || finished) return;
            status = text;
            tray.Text = text.Length > MaxTooltip ? text.Substring(0, MaxTooltip) : text;
            Log("status: " + state);
        }

        /// <summary>A press on the desktop calls in a blast there; holding the button turns it into a barrage.</summary>
        void OnMouse(int message, int x, int y)
        {
            if (message == MouseHook.Up)
            {
                // Every mouse release in Windows arrives here; only the end of a blast matters to the page.
                if (!pressing) return;
                pressing = false;
                foreach (var w in walls) w.Run("window.battle && battle.release()");
                return;
            }

            if (!settings.Clicks) return;
            if (!Desktop.IsDesktop(Native.WindowFromPoint(new Native.POINT(x, y)))) return;
            foreach (var w in walls)
            {
                var b = w.Screen.Bounds;
                if (!b.Contains(x, y)) continue;
                w.Run(string.Format(CultureInfo.InvariantCulture, "window.battle && battle.blast({0:0.0000},{1:0.0000})",
                    (x - b.Left) / (double)b.Width, (y - b.Top) / (double)b.Height));
                pressing = true;
            }
        }

        /// <summary>Sends the current settings to every wall (a sleeping one applies them on waking) and saves them.</summary>
        void SettingsChanged()
        {
            foreach (var w in walls) w.ApplySettings();
            if (!test) settings.Save();
        }

        ContextMenuStrip BuildMenu()
        {
            var menu = new ContextMenuStrip();
            var refreshChecks = new List<Action>();
            menu.Opening += delegate { foreach (var refresh in refreshChecks) refresh(); };

            var title = new ToolStripMenuItem("Pixel Battle: your live wallpaper");
            title.Enabled = false;
            menu.Items.Add(title);
            menu.Items.Add(new ToolStripSeparator());

            pauseItem = new ToolStripMenuItem("Pause", null, delegate
            {
                paused = !paused;
                pauseItem.Text = paused ? "Resume" : "Pause";
                Watch();
            });
            menu.Items.Add(pauseItem);
            menu.Items.Add(Choice("Speed", new[] { "1x", "2x", "4x" }, new double[] { 1, 2, 4 },
                delegate { return settings.Speed; },
                delegate (double v) { settings.Speed = v; SettingsChanged(); }));
            menu.Items.Add(Choice("Zoom", new[] { "100%", "75%", "50%" }, new double[] { 100, 75, 50 },
                delegate { return settings.Zoom; },
                delegate (double v) { settings.Zoom = (int)v; SettingsChanged(); }));
            menu.Items.Add(Choice("Frame rate", new[] { "20 fps (lightest)", "30 fps", "60 fps (smoothest)" },
                new double[] { 20, 30, 60 },
                delegate { return settings.Fps; },
                delegate (double v) { settings.Fps = (int)v; SettingsChanged(); }));
            menu.Items.Add(Choice("Screens", new[] { "Main screen", "Every screen" }, new double[] { 0, 1 },
                delegate { return settings.AllScreens ? 1 : 0; },
                delegate (double v) { settings.AllScreens = v > 0; settings.Save(); Rebuild(); }));
            menu.Items.Add(Toggle(refreshChecks, "Clicking the desktop calls in a blast",
                delegate { return settings.Clicks; },
                delegate (bool v) { settings.Clicks = v; settings.Save(); }));
            menu.Items.Add(Toggle(refreshChecks, "Sleep on battery",
                delegate { return settings.PauseOnBattery; },
                delegate (bool v) { settings.PauseOnBattery = v; settings.Save(); Watch(); }));
            menu.Items.Add(Toggle(refreshChecks, "Start with Windows", StartsWithWindows, SetStartWithWindows));
            menu.Items.Add(new ToolStripMenuItem("New battle", null, delegate
            {
                foreach (var w in walls) w.Run("location.reload()");
            }));
            menu.Items.Add(new ToolStripSeparator());
            menu.Items.Add(new ToolStripMenuItem("Exit (puts your own wallpaper back)", null, delegate { Finish(); }));
            return menu;
        }

        /// <summary>A submenu of options, with the current one ticked whenever it opens.</summary>
        static ToolStripMenuItem Choice(string text, string[] labels, double[] values, Func<double> get, Action<double> set)
        {
            var item = new ToolStripMenuItem(text);
            for (int i = 0; i < labels.Length; i++)
            {
                double value = values[i];
                var option = new ToolStripMenuItem(labels[i]);
                option.Click += delegate { set(value); };
                item.DropDownItems.Add(option);
            }
            item.DropDownOpening += delegate
            {
                for (int i = 0; i < values.Length; i++)
                    ((ToolStripMenuItem)item.DropDownItems[i]).Checked = Math.Abs(get() - values[i]) < 0.01;
            };
            return item;
        }

        static ToolStripMenuItem Toggle(List<Action> refreshChecks, string text, Func<bool> get, Action<bool> set)
        {
            var item = new ToolStripMenuItem(text);
            item.Click += delegate { set(!get()); };
            refreshChecks.Add(delegate { item.Checked = get(); });
            return item;
        }

        static bool StartsWithWindows()
        {
            using (var key = Registry.CurrentUser.OpenSubKey(RunKey))
            {
                return key != null && key.GetValue("PixelBattle") != null;
            }
        }

        static void SetStartWithWindows(bool on)
        {
            try
            {
                using (var key = Registry.CurrentUser.CreateSubKey(RunKey))
                {
                    if (on) key.SetValue("PixelBattle", "\"" + Application.ExecutablePath + "\" --startup");
                    else key.DeleteValue("PixelBattle", false);
                }
            }
            catch (Exception) { }
        }

        /// <summary>Removes every wall, restores the normal wallpaper and exits.</summary>
        void Finish()
        {
            if (finished) return;
            finished = true;
            watch.Stop();
            SystemEvents.DisplaySettingsChanged -= OnDisplays;
            SystemEvents.SessionSwitch -= OnSession;
            if (hook != null) hook.Dispose();
            if (signals != null) signals.DestroyHandle();
            foreach (var w in walls) w.Close();
            walls.Clear();
            Desktop.Repaint();
            tray.Visible = false;
            tray.Dispose();

            if (logging)
            {
                Log("closed");
                try
                {
                    Directory.CreateDirectory(Settings.Folder);
                    File.WriteAllText(Path.Combine(Settings.Folder, test ? "selftest.log" : "log.txt"), log.ToString());
                }
                catch (Exception) { }
            }
            ExitThread();
        }
    }

    /// <summary>The battle on one screen: a borderless form hosting WebView2, embedded behind the desktop icons.</summary>
    sealed class Wall : Form
    {
        public readonly Screen Screen;
        /// <summary>The last sleep/wake decision logged for this wall, so only changes are logged.</summary>
        public string LastDecision = "";
        readonly Action<string> log;
        readonly Func<string> settingsScript;
        WebView2 view;
        bool awake = true;
        bool sleeping;
        bool loaded;
        string lastReport = "";

        public Wall(Screen screen, Action<string> log, Func<string> settingsScript)
        {
            Screen = screen;
            this.log = log;
            this.settingsScript = settingsScript;
            FormBorderStyle = FormBorderStyle.None;
            ShowInTaskbar = false;
            StartPosition = FormStartPosition.Manual;
            BackColor = Color.FromArgb(5, 6, 15);
            Bounds = screen.Bounds;
            Text = "Pixel Battle";
        }

        protected override CreateParams CreateParams
        {
            get
            {
                // Never takes focus and stays out of the taskbar and Alt+Tab.
                var cp = base.CreateParams;
                cp.ExStyle |= Native.WS_EX_TOOLWINDOW | Native.WS_EX_NOACTIVATE;
                return cp;
            }
        }

        protected override bool ShowWithoutActivation
        {
            get { return true; }
        }

        public async void Open(CoreWebView2Environment env, string folder, string query)
        {
            try
            {
                view = new WebView2();
                view.Dock = DockStyle.Fill;
                view.DefaultBackgroundColor = BackColor;
                Controls.Add(view);

                // Embedded before and after Show so it never appears as a normal window.
                Desktop.Embed(Handle, Screen.Bounds);
                Show();
                Desktop.Embed(Handle, Screen.Bounds);

                await view.EnsureCoreWebView2Async(env);
                var core = view.CoreWebView2;
                core.Settings.AreDefaultContextMenusEnabled = false;
                core.Settings.AreDevToolsEnabled = false;
                core.Settings.IsStatusBarEnabled = false;
                core.Settings.IsZoomControlEnabled = false;
                core.Settings.AreBrowserAcceleratorKeysEnabled = false;
                core.SetVirtualHostNameToFolderMapping("pixelbattle.local", folder, CoreWebView2HostResourceAccessKind.Allow);
                core.WebMessageReceived += delegate (object sender, CoreWebView2WebMessageReceivedEventArgs e)
                {
                    lastReport = e.TryGetWebMessageAsString();
                    if (log != null) log("page: " + lastReport);
                };
                core.NavigationCompleted += delegate (object sender, CoreWebView2NavigationCompletedEventArgs e)
                {
                    if (log != null) log("page loaded: " + e.IsSuccess);
                    // Every load, "New battle" included, starts from the query string: bring it up to date.
                    loaded = e.IsSuccess;
                    ApplySettings();
                };
                core.Navigate("https://pixelbattle.local/index.html" + query);
            }
            catch (Exception e)
            {
                if (log != null) log("wall failed: " + e.Message);
            }
        }

        /// <summary>Runs a script in the page, if it is awake.</summary>
        public void Run(string js)
        {
            if (view != null && view.CoreWebView2 != null && awake) view.CoreWebView2.ExecuteScriptAsync(js);
        }

        /// <summary>Sends the current settings, if the page is loaded and awake; otherwise they are sent on load or wake.</summary>
        public void ApplySettings()
        {
            if (loaded) Run(settingsScript());
        }

        /// <summary>Awake, the page is shown and running; asleep, it is hidden and suspended.</summary>
        public async void Awake(bool on)
        {
            if (view == null || view.CoreWebView2 == null || on == awake || sleeping) return;
            awake = on;
            try
            {
                if (on)
                {
                    view.CoreWebView2.Resume();
                    view.Visible = true;
                    ApplySettings();
                    if (log != null) log(Screen.DeviceName + ": awake");
                }
                else
                {
                    view.Visible = false;
                    sleeping = true;
                    bool suspended = await view.CoreWebView2.TrySuspendAsync();
                    sleeping = false;
                    if (log != null) log(Screen.DeviceName + ": asleep (page suspended: " + suspended + ")");
                }
            }
            catch (Exception e)
            {
                sleeping = false;
                if (log != null) log(Screen.DeviceName + ": couldn't sleep: " + e.Message);
            }
        }

        /// <summary>Where the wall is and what its page last reported, for the self-test log.</summary>
        public string Report()
        {
            var parent = Native.GetParent(Handle);
            Native.RECT r;
            Native.GetWindowRect(Handle, out r);
            return string.Format(CultureInfo.InvariantCulture,
                "wall on {0}: parent {1}, at {2},{3} {4}x{5}, visible {6}, page says {7}",
                Screen.DeviceName, Native.ClassOf(parent), r.Left, r.Top, r.Right - r.Left, r.Bottom - r.Top,
                Native.IsWindowVisible(Handle), lastReport);
        }
    }

    /// <summary>Finds the window behind the desktop icons and embeds walls in it.</summary>
    static class Desktop
    {
        const uint SpawnWorkerW = 0x052C;
        static IntPtr parent;
        static IntPtr icons;
        static bool raised;

        /// <summary>
        /// Asks Progman to create a WorkerW behind the icons, then finds where a wallpaper goes.
        /// Up to Windows 11 23H2 that is the top-level WorkerW after the one holding the icons
        /// (SHELLDLL_DefView). From 24H2 the desktop is "raised": the icons and the WorkerW are both
        /// children of Progman, and the wallpaper goes in Progman between them.
        /// </summary>
        public static bool Find()
        {
            var progman = Native.FindWindow("Progman", null);
            if (progman == IntPtr.Zero) return false;

            IntPtr result;
            Native.SendMessageTimeout(progman, SpawnWorkerW, new IntPtr(0xD), new IntPtr(0x1), 0, 1000, out result);
            Native.SendMessageTimeout(progman, SpawnWorkerW, IntPtr.Zero, IntPtr.Zero, 0, 1000, out result);

            IntPtr worker = IntPtr.Zero;
            Native.EnumWindows(delegate (IntPtr top, IntPtr lParam)
            {
                if (Native.FindWindowEx(top, IntPtr.Zero, "SHELLDLL_DefView", null) != IntPtr.Zero)
                {
                    var next = Native.FindWindowEx(IntPtr.Zero, top, "WorkerW", null);
                    if (next != IntPtr.Zero) worker = next;
                }
                return true;
            }, IntPtr.Zero);

            icons = Native.FindWindowEx(progman, IntPtr.Zero, "SHELLDLL_DefView", null);
            if (icons != IntPtr.Zero && Native.FindWindowEx(progman, IntPtr.Zero, "WorkerW", null) != IntPtr.Zero)
            {
                parent = progman;
                raised = true;
                return true;
            }
            if (worker != IntPtr.Zero)
            {
                parent = worker;
                raised = false;
                return true;
            }
            return false;
        }

        public static string Describe()
        {
            return (raised ? "raised (24H2 on): in Progman, under the icons" : "classic: in the WorkerW behind the icons")
                + ", parent " + Native.ClassOf(parent);
        }

        public static bool Alive()
        {
            return parent != IntPtr.Zero && Native.IsWindow(parent);
        }

        /// <summary>Makes <paramref name="hwnd"/> a child of the desktop covering <paramref name="bounds"/> (screen coordinates), under the icons.</summary>
        public static void Embed(IntPtr hwnd, Rectangle bounds)
        {
            if (parent == IntPtr.Zero) return;
            long style = Native.GetWindowLongPtr(hwnd, Native.GWL_STYLE).ToInt64();
            style &= ~(long)(Native.WS_POPUP | Native.WS_CAPTION | Native.WS_THICKFRAME | Native.WS_SYSMENU);
            Native.SetWindowLongPtr(hwnd, Native.GWL_STYLE, new IntPtr(style | Native.WS_CHILD));
            if (Native.GetParent(hwnd) != parent) Native.SetParent(hwnd, parent);

            var origin = new[] { new Native.POINT(bounds.Left, bounds.Top) };
            Native.MapWindowPoints(IntPtr.Zero, parent, origin, 1);
            uint flags = Native.SWP_NOACTIVATE | Native.SWP_SHOWWINDOW | Native.SWP_FRAMECHANGED;
            if (raised)
                Native.SetWindowPos(hwnd, icons, origin[0].X, origin[0].Y, bounds.Width, bounds.Height, flags);
            else
                Native.SetWindowPos(hwnd, IntPtr.Zero, origin[0].X, origin[0].Y, bounds.Width, bounds.Height,
                    flags | Native.SWP_NOZORDER);
        }

        /// <summary>Whether a window is the desktop itself: its icons or the background between them.</summary>
        public static bool IsDesktop(IntPtr hwnd)
        {
            var name = Native.ClassOf(hwnd);
            if (name == "SysListView32") name = Native.ClassOf(Native.GetParent(hwnd));
            return name == "SHELLDLL_DefView" || name == "WorkerW" || name == "Progman";
        }

        /// <summary>Re-applies the current wallpaper (without saving anything) so the desktop repaints it.</summary>
        public static void Repaint()
        {
            var path = new StringBuilder(520);
            if (Native.SystemParametersInfo(Native.SPI_GETDESKWALLPAPER, path.Capacity, path, 0))
                Native.SystemParametersInfo(Native.SPI_SETDESKWALLPAPER, 0, path.ToString(), 0);
        }
    }

    /// <summary>Measures how much of a screen's desktop is hidden behind other windows.</summary>
    static class Covered
    {
        static readonly HashSet<string> ShellClasses = new HashSet<string>
        {
            "Progman", "WorkerW", "Shell_TrayWnd", "Shell_SecondaryTrayWnd", "SHELLDLL_DefView", "Windows.UI.Core.CoreWindow",
        };
        static readonly int ProcessId = Process.GetCurrentProcess().Id;
        const int CellSize = 32;

        /// <summary>Hidden at least this much, the battle sleeps: a sliver isn't worth drawing the whole scene for.</summary>
        public const double Threshold = 0.97;

        /// <summary>
        /// The fraction (0–1) of the screen's work area covered by real windows, sampled on a grid.
        /// Counts every visible window together by its visible frame, so two snapped windows count
        /// like one maximised one. Ignores minimised and cloaked windows (other virtual desktops),
        /// click-through overlays, the shell's own windows and this app's.
        /// </summary>
        public static double Share(Screen screen)
        {
            var area = screen.WorkingArea;
            int cols = Math.Max(1, area.Width / CellSize);
            int rows = Math.Max(1, area.Height / CellSize);
            var xs = new double[cols];
            var ys = new double[rows];
            for (int i = 0; i < cols; i++) xs[i] = area.Left + (i + 0.5) * area.Width / cols;
            for (int j = 0; j < rows; j++) ys[j] = area.Top + (j + 0.5) * area.Height / rows;
            var hidden = new bool[cols * rows];
            int count = 0;

            Native.EnumWindows(delegate (IntPtr h, IntPtr lParam)
            {
                if (!Native.IsWindowVisible(h) || Native.IsIconic(h)) return true;
                int cloaked;
                if (Native.DwmGetWindowAttribute(h, Native.DWMWA_CLOAKED, out cloaked, 4) == 0 && cloaked != 0) return true;
                uint pid;
                Native.GetWindowThreadProcessId(h, out pid);
                if (pid == ProcessId) return true;
                if ((Native.GetWindowLongPtr(h, Native.GWL_EXSTYLE).ToInt64() & Native.WS_EX_TRANSPARENT) != 0) return true;
                if (ShellClasses.Contains(Native.ClassOf(h))) return true;

                // The visible frame, without the invisible resize borders GetWindowRect includes.
                Native.RECT r;
                int size = Marshal.SizeOf(typeof(Native.RECT));
                if (Native.DwmGetWindowAttribute(h, Native.DWMWA_EXTENDED_FRAME_BOUNDS, out r, size) != 0
                    && !Native.GetWindowRect(h, out r))
                    return true;
                if (r.Right <= area.Left || r.Left >= area.Right || r.Bottom <= area.Top || r.Top >= area.Bottom) return true;

                for (int j = 0; j < rows; j++)
                {
                    if (ys[j] < r.Top || ys[j] >= r.Bottom) continue;
                    for (int i = 0; i < cols; i++)
                    {
                        if (xs[i] < r.Left || xs[i] >= r.Right || hidden[j * cols + i]) continue;
                        hidden[j * cols + i] = true;
                        count++;
                    }
                }
                return count < cols * rows;
            }, IntPtr.Zero);
            return count / (double)(cols * rows);
        }

        public static bool Over(Screen screen)
        {
            return Share(screen) >= Threshold;
        }
    }

    /// <summary>A low-level mouse hook reporting left-button presses and releases anywhere on screen.</summary>
    sealed class MouseHook : IDisposable
    {
        public const int Down = 0x0201;
        public const int Up = 0x0202;
        const int WH_MOUSE_LL = 14;
        readonly Native.HookProc proc;
        readonly IntPtr handle;
        readonly Action<int, int, int> onMouse;

        public MouseHook(Action<int, int, int> onMouse)
        {
            this.onMouse = onMouse;
            // Held in a field so the delegate isn't garbage collected while Windows still calls it.
            proc = Hook;
            handle = Native.SetWindowsHookEx(WH_MOUSE_LL, proc, Native.GetModuleHandle(null), 0);
        }

        IntPtr Hook(int code, IntPtr wParam, IntPtr lParam)
        {
            if (code >= 0)
            {
                int message = wParam.ToInt32();
                if (message == Down || message == Up)
                {
                    var pt = (Native.POINT)Marshal.PtrToStructure(lParam, typeof(Native.POINT));
                    try { onMouse(message, pt.X, pt.Y); }
                    catch (Exception) { }
                }
            }
            return Native.CallNextHookEx(handle, code, wParam, lParam);
        }

        public void Dispose()
        {
            if (handle != IntPtr.Zero) Native.UnhookWindowsHookEx(handle);
        }
    }

    /// <summary>A hidden top-level window that receives the shell's "TaskbarCreated" broadcast when Explorer restarts.</summary>
    sealed class Signals : NativeWindow
    {
        readonly int taskbarCreated = Native.RegisterWindowMessage("TaskbarCreated");
        readonly Action onExplorerRestart;

        public Signals(Action onExplorerRestart)
        {
            this.onExplorerRestart = onExplorerRestart;
            CreateHandle(new CreateParams());
        }

        protected override void WndProc(ref Message m)
        {
            if (m.Msg == taskbarCreated) onExplorerRestart();
            base.WndProc(ref m);
        }
    }

