import report from "@/data/test-report.json";
import { cn } from "@/lib/utils";
import Reveal from "@/components/fx/Reveal";

/** Shape of src/data/test-report.json, written by scripts/test-report.mjs. */
export interface TestReport {
  generatedAt: string;
  threshold: number;
  tests: { total: number; passed: number; failed: number; files: number; suites?: number };
  coverage: { statements: number; branches: number; functions: number; lines: number };
}

const METRICS: { key: keyof TestReport["coverage"]; label: string }[] = [
  { key: "statements", label: "Statements" },
  { key: "branches", label: "Branches" },
  { key: "functions", label: "Functions" },
  { key: "lines", label: "Lines" },
];

const formatDate = (iso: string) => {
  const d = new Date(iso);
  return Number.isNaN(d.getTime())
    ? "—"
    : d.toLocaleDateString("en-GB", { day: "2-digit", month: "short", year: "numeric" });
};

/**
 * Unit-test + coverage results, regenerated by `npm run test:report` on every deploy.
 * Passing means no failures and every coverage metric at or above the threshold.
 */
export default function QualityReport({ data = report as TestReport }: { data?: TestReport }) {
  const lowest = Math.min(...METRICS.map((m) => data.coverage[m.key]));
  const passing = data.tests.failed === 0 && data.tests.total > 0 && lowest >= data.threshold;

  return (
    <Reveal as="section" className="qa" aria-label="Automated test results">
      <div className="qa__head">
        <span className={cn("qa__status", passing ? "is-ok" : "is-fail")}>
          <i aria-hidden="true" />
          {passing ? "All checks passing" : "Checks failing"}
        </span>
        <span className="mono-label">Unit tests · Vitest · v8 coverage</span>
      </div>

      <div className="qa__grid">
        <div className="qa__tests">
          <span className="qa__big">
            {data.tests.passed}/{data.tests.total}
          </span>
          <span className="mono-label">
            tests passing · {data.tests.files} test files
          </span>
        </div>
        {METRICS.map(({ key, label }) => {
          const value = data.coverage[key];
          return (
            <div className="qa__metric" key={key}>
              <div className="qa__row">
                <span className="mono-label">{label}</span>
                <span className={cn("qa__val", value < data.threshold && "is-low")}>{value.toFixed(1)}%</span>
              </div>
              <span className="qa__bar" role="meter" aria-valuenow={value} aria-valuemin={0} aria-valuemax={100} aria-label={`${label} coverage`}>
                <i style={{ transform: `scaleX(${Math.min(1, value / 100)})` }} />
                <b style={{ left: `${data.threshold}%` }} aria-hidden="true" />
              </span>
            </div>
          );
        })}
      </div>

      <p className="mono-label qa__foot">
        Coverage threshold {data.threshold}% · verified {formatDate(data.generatedAt)}
      </p>
    </Reveal>
  );
}
