/**
 * The facts about every prop (size, debris colour, what lights up, burns or smokes) and which
 * backdrops use it. art.ts and catalog.ts paint them, level.ts places them, game.ts blows them up.
 */
import type { Backdrop } from "./themes";
import { CATALOG } from "./catalog";

export interface AssetDef {
  /** Size in scene px; it stands on its bottom edge, centred on its x */
  w: number;
  h: number;
  /** The colour of the bits it breaks into */
  debris: string;
  /** Blast radius, for props that explode when hit */
  boom?: number;
  /** Lit spots: x, y from its top left, colour, and blink rate, where 0 is steady */
  lights?: [number, number, string, number][];
  /** Where it burns, as x, y from its top left */
  flames?: [number, number][];
  /** Where it smokes */
  smoke?: [number, number][];
  /** Mounted half way up a wall, or hanging from the ceiling */
  wall?: boolean;
  hang?: boolean;
}

